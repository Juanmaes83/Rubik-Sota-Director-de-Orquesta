// ---- tracking (ported from finger-frame-effect main.js) ----
function toPixel(lm) {
  return {
    x: sourceDraw.x + lm.x * sourceDraw.width,
    y: sourceDraw.y + lm.y * sourceDraw.height,
  };
}
function dist(a, b) {
  return Math.hypot(a.x - b.x, a.y - b.y);
}
function lerpPt(a, b, t) {
  return { x: a.x + (b.x - a.x) * t, y: a.y + (b.y - a.y) * t };
}
function polygonArea(pts) {
  let a = 0;
  for (let i = 0; i < pts.length; i++) {
    const p = pts[i], q = pts[(i + 1) % pts.length];
    a += p.x * q.y - q.x * p.y;
  }
  return Math.abs(a / 2);
}

function computeQuad(hands) {
  if (hands.length !== 2) return null;
  const info = hands.map((lm) => ({
    index: toPixel(lm[INDEX_TIP]),
    thumb: toPixel(lm[THUMB_TIP]),
    wristX: toPixel(lm[WRIST]).x,
    scale: dist(toPixel(lm[WRIST]), toPixel(lm[MIDDLE_MCP])) + 1,
  }));
  const needed = frameActive ? 0.2 : 0.75;
  for (const hd of info) {
    if (dist(hd.thumb, hd.index) < hd.scale * needed) return null;
  }
  info.sort((a, b) => a.wristX - b.wristX);
  const [A, B] = info;
  const pts = [A.index, B.index, B.thumb, A.thumb];
  const cx = pts.reduce((s, p) => s + p.x, 0) / 4;
  const cy = pts.reduce((s, p) => s + p.y, 0) / 4;
  const hull = [...pts].sort(
    (a, b) => Math.atan2(a.y - cy, a.x - cx) - Math.atan2(b.y - cy, b.x - cx)
  );
  const minArea = frameActive ? 0.0005 : 0.005;
  if (polygonArea(hull) < canvas.width * canvas.height * minArea) return null;
  return pts;
}

function updateTracker(hands) {
  const target = computeQuad(hands);
  if (target) {
    if (!corners) {
      lostFrames = 0;
      frameActive = true;
      jumpFrames = 0;
      corners = target;
      presence = Math.min(1, presence + 0.12);
    } else {
      const moved = target.reduce((s, p, i) => s + dist(p, corners[i]), 0) / 4;
      if (moved > canvas.width * 0.3 && ++jumpFrames < JUMP_CONFIRM_FRAMES) {
        if (++lostFrames > MAX_LOST_FRAMES) presence = Math.max(0, presence - 0.05);
      } else {
        lostFrames = 0;
        frameActive = true;
        jumpFrames = 0;
        const alpha = Math.min(0.85, Math.max(0.35, moved / (canvas.width * 0.05)));
        corners = corners.map((c, i) => lerpPt(c, target[i], alpha));
        presence = Math.min(1, presence + 0.12);
      }
    }
  } else if (corners && ++lostFrames <= MAX_LOST_FRAMES) {
    presence = Math.min(1, presence + 0.12);
  } else {
    presence = Math.max(0, presence - 0.05);
    if (presence === 0) {
      corners = null;
      frameActive = false;
      jumpFrames = 0;
    }
  }
}

// ---- rendering ----
function quadPath(q) {
  ctx.beginPath();
  ctx.moveTo(q[0].x, q[0].y);
  for (let i = 1; i < 4; i++) ctx.lineTo(q[i].x, q[i].y);
  ctx.closePath();
}

function resetTrackingState() {
  corners = null;
  presence = 0;
  frameActive = false;
  lostFrames = 0;
  jumpFrames = 0;
  lastVideoTime = -1;
}

function expandQuad(q, amount) {
  const cx = q.reduce((sum, p) => sum + p.x, 0) / q.length;
  const cy = q.reduce((sum, p) => sum + p.y, 0) / q.length;
  const factor = Math.max(0.35, 1 + amount);
  return q.map((p) => ({
    x: cx + (p.x - cx) * factor,
    y: cy + (p.y - cy) * factor,
  }));
}

function quadBounds(q) {
  const xs = q.map((p) => p.x);
  const ys = q.map((p) => p.y);
  const minX = Math.min(...xs);
  const maxX = Math.max(...xs);
  const minY = Math.min(...ys);
  const maxY = Math.max(...ys);
  return { x: minX, y: minY, width: maxX - minX, height: maxY - minY };
}

function drawOutsideDim(q, alpha) {
  if (alpha <= 0) return;
  ctx.save();
  ctx.globalAlpha = presence * alpha;
  ctx.fillStyle = "#000";
  ctx.beginPath();
  ctx.rect(0, 0, canvas.width, canvas.height);
  ctx.moveTo(q[0].x, q[0].y);
  for (let i = 3; i >= 0; i--) ctx.lineTo(q[i].x, q[i].y);
  ctx.closePath();
  ctx.fill("evenodd");
  ctx.restore();
}

function drawCoverSource(source, bounds, scale = 1, offsetX = 0, offsetY = 0) {
  const sourceWidth = source.videoWidth || source.naturalWidth || source.width;
  const sourceHeight = source.videoHeight || source.naturalHeight || source.height;
  if (!sourceWidth || !sourceHeight || !bounds.width || !bounds.height) return false;
  const coverScale = Math.max(bounds.width / sourceWidth, bounds.height / sourceHeight) * scale;
  const drawWidth = sourceWidth * coverScale;
  const drawHeight = sourceHeight * coverScale;
  const x = bounds.x + (bounds.width - drawWidth) / 2 + offsetX * bounds.width;
  const y = bounds.y + (bounds.height - drawHeight) / 2 + offsetY * bounds.height;
  ctx.drawImage(source, x, y, drawWidth, drawHeight);
  return true;
}

function drawWindow(q) {
  const composer = readComposer();
  const expanded = expandQuad(q, composer.frameExpand);
  const bounds = quadBounds(expanded);
  drawOutsideDim(expanded, composer.outsideDim);
  ctx.save();
  quadPath(expanded);
  ctx.clip();
  ctx.globalAlpha = presence;
  if (portalElement && (portalType === "image" || portalElement.readyState >= 2)) {
    drawCoverSource(portalElement, bounds, composer.portalScale, composer.portalOffsetX, composer.portalOffsetY);
  } else if (haveAI) {
    ctx.drawImage(sty, sourceDraw.x, sourceDraw.y, sourceDraw.width, sourceDraw.height);
  } else {
    ctx.filter = "hue-rotate(140deg) saturate(1.7) contrast(1.15)";
    ctx.drawImage(orig, sourceDraw.x, sourceDraw.y, sourceDraw.width, sourceDraw.height);
    ctx.filter = "none";
  }
  ctx.restore();
  ctx.globalAlpha = 1;
  return expanded;
}

function drawOutline(q, t, glow = 0.55) {
  ctx.save();
  ctx.globalAlpha = presence;
  if (glow > 0) {
    quadPath(q);
    ctx.setLineDash([]);
    ctx.lineWidth = Math.max(6, canvas.width * 0.006) * glow;
    ctx.strokeStyle = "rgba(255, 194, 75, 0.8)";
    ctx.shadowColor = "rgba(255, 107, 94, 0.75)";
    ctx.shadowBlur = Math.max(16, canvas.width * 0.018) * glow;
    ctx.stroke();
  }
  quadPath(q);
  ctx.setLineDash([10, 8]);
  ctx.lineDashOffset = -t * 40;
  ctx.lineWidth = Math.max(2, canvas.width * 0.002);
  ctx.strokeStyle = "rgba(255,255,255,0.95)";
  ctx.shadowColor = "rgba(0,0,0,0.5)";
  ctx.shadowBlur = 6;
  ctx.stroke();
  ctx.setLineDash([]);
  ctx.lineDashOffset = 0;
  ctx.shadowBlur = 0;
  q.forEach((p, i) => {
    const r = 7 + Math.sin(t * 3 + i * 1.5) * 1.5;
    const halo = (t * 0.8 + i * 0.25) % 1;
    ctx.beginPath();
    ctx.arc(p.x, p.y, r + halo * 14, 0, Math.PI * 2);
    ctx.strokeStyle = `rgba(255,255,255,${0.5 * (1 - halo) * presence})`;
    ctx.lineWidth = 2;
    ctx.stroke();
    ctx.beginPath();
    ctx.arc(p.x, p.y, r, 0, Math.PI * 2);
    ctx.fillStyle = "#fff";
    ctx.fill();
    ctx.beginPath();
    ctx.arc(p.x, p.y, r, 0, Math.PI * 2);
    ctx.strokeStyle = "rgba(0,0,0,0.25)";
    ctx.lineWidth = 1.5;
    ctx.stroke();
  });
  ctx.restore();
}

function drawRoundRect(x, y, width, height, radius) {
  const r = Math.min(radius, width / 2, height / 2);
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + width, y, x + width, y + height, r);
  ctx.arcTo(x + width, y + height, x, y + height, r);
  ctx.arcTo(x, y + height, x, y, r);
  ctx.arcTo(x, y, x + width, y, r);
  ctx.closePath();
}

